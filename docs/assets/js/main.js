const categoryColors = { hub: '#b989ff', protocol: '#58e1ff', agent: '#a6f17a', tool: '#ffc56c', system: '#658dff', other: '#91a5bd' };
let currentLang = localStorage.getItem('irsanai_lang') || 'de';
if (!translations[currentLang]) currentLang = 'de';
let allRepos = [];
let manifest = null;
let currentFilter = 'all';
let currentLayer = null;
let currentView = 'cards';
let searchQuery = '';
let sortMode = 'recent';

const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];
const t = (key) => translations[currentLang][key] ?? key;

function escapeHTML(value) {
  return String(value ?? '').replace(/[&<>'"]/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' }[char]));
}
function repoId(name) { return `repo-${String(name).replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`; }
function categoryLabel(category) { return translations[currentLang].categories[category] || translations[currentLang].categories.other; }
function statusLabel(status) { return translations[currentLang].statuses[status] || status; }
function formatDate(value) {
  if (!value) return '—';
  const date = new Date(value);
  return Number.isNaN(date.valueOf()) ? '—' : new Intl.DateTimeFormat(currentLang === 'de' ? 'de-DE' : 'en-US', { day: '2-digit', month: 'short', year: 'numeric' }).format(date);
}
function relativeTime(value) {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.valueOf())) return '—';
  const seconds = Math.round((date.getTime() - Date.now()) / 1000);
  const units = [[31536000, 'year'], [2592000, 'month'], [86400, 'day'], [3600, 'hour'], [60, 'minute']];
  for (const [size, unit] of units) {
    if (Math.abs(seconds) >= size) return new Intl.RelativeTimeFormat(currentLang === 'de' ? 'de-DE' : 'en-US', { numeric: 'auto' }).format(Math.round(seconds / size), unit);
  }
  return new Intl.RelativeTimeFormat(currentLang === 'de' ? 'de-DE' : 'en-US', { numeric: 'auto' }).format(seconds, 'second');
}
function ageDays(value) {
  if (!value) return 9999;
  const timestamp = new Date(value).getTime();
  return Number.isNaN(timestamp) ? 9999 : Math.max(0, (Date.now() - timestamp) / 86400000);
}
function freshnessScore(repo) { const age = ageDays(repo.last_pushed); return age <= 30 ? 100 : age <= 90 ? 82 : age <= 180 ? 58 : age <= 365 ? 32 : 12; }
function semanticScore(repo) { return Math.round((repo.description_de && repo.description_en ? 100 : repo.description || repo.description_de || repo.description_en ? 65 : 20) * (repo.canonical === false ? .85 : 1)); }
function pageScore(repo) { return repo.pages_detected ? 100 : 0; }
function resonanceScore(repo) { return Math.round(freshnessScore(repo) * .5 + semanticScore(repo) * .3 + pageScore(repo) * .2); }
function filteredRepos() {
  const query = searchQuery.trim().toLowerCase();
  return allRepos.filter(repo => {
    const matchesCategory = currentFilter === 'all' || repo.category === currentFilter;
    const matchesLayer = !currentLayer || repo.layer === currentLayer;
    const searchable = [repo.name, repo.description, repo.description_de, repo.description_en, repo.layer, repo.role].filter(Boolean).join(' ').toLowerCase();
    return matchesCategory && matchesLayer && (!query || searchable.includes(query));
  }).sort((a, b) => {
    if (sortMode === 'name') return a.name.localeCompare(b.name);
    if (sortMode === 'stars') return (b.stars || 0) - (a.stars || 0) || a.name.localeCompare(b.name);
    if (sortMode === 'resonance') return resonanceScore(b) - resonanceScore(a) || a.name.localeCompare(b.name);
    return new Date(b.last_pushed || 0) - new Date(a.last_pushed || 0);
  });
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.documentElement.dataset.lang = currentLang;
  $$('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  $$('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  $$('.lang-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === currentLang));
  if (manifest) $('#footer-version').textContent = t('manifest_version').replace('{version}', manifest.version);
}

function updateStats() {
  const total = allRepos.length;
  const active = allRepos.filter(repo => repo.sync_status === 'ACTIVE' || ageDays(repo.last_pushed) <= 30).length;
  const stars = allRepos.reduce((sum, repo) => sum + Number(repo.stars || 0), 0);
  const latest = allRepos[0]?.last_pushed;
  $('#total-repos').textContent = total;
  $('#active-repos').textContent = active;
  $('#total-stars').textContent = stars;
  $('#last-update-time').textContent = manifest ? formatDate(manifest.last_updated) : formatDate(latest);
  $('#manifest-age').textContent = manifest ? `${t('updated')} ${relativeTime(manifest.last_updated)}` : '—';
  $('#result-count').textContent = filteredRepos().length;
}

function updateInstrument() {
  if (!allRepos.length) return;
  const freshness = Math.round(allRepos.reduce((sum, repo) => sum + freshnessScore(repo), 0) / allRepos.length);
  const semantic = Math.round(allRepos.reduce((sum, repo) => sum + semanticScore(repo), 0) / allRepos.length);
  const pages = Math.round(allRepos.reduce((sum, repo) => sum + pageScore(repo), 0) / allRepos.length);
  const score = Math.round(freshness * .5 + semantic * .3 + pages * .2);
  const label = score >= 76 ? t('pulse_stable') : score >= 48 ? t('pulse_forming') : t('pulse_quiet');
  $('#pulse-score').textContent = score;
  $('#pulse-label').textContent = label;
  $('#instrument-state').textContent = score >= 76 ? 'STABLE' : score >= 48 ? 'FORMING' : 'QUIET';
  [['freshness', freshness], ['semantic', semantic], ['pages', pages]].forEach(([key, value]) => { $(`#factor-${key}`).style.width = `${value}%`; $(`#factor-${key}-value`).textContent = `${value}%`; });
  $('#pulse-orb').dataset.score = score;
}

function createRepoCard(repo) {
  const card = document.createElement('article');
  card.className = 'repo-card';
  card.id = repoId(repo.name);
  card.style.setProperty('--card-accent', categoryColors[repo.category] || categoryColors.other);
  const desc = currentLang === 'de' ? (repo.description_de || repo.description || t('no_desc')) : (repo.description_en || repo.description || t('no_desc'));
  const roleText = currentLang === 'de' ? (repo.role_de || repo.description_de || repo.role || '') : (repo.role_en || repo.role || repo.description_en || '');
  const avatar = repo.avatar ? `<img class="repo-avatar repo-image" src="${escapeHTML(repo.avatar)}" alt="" loading="lazy">` : `<span class="repo-avatar avatar-fallback">${escapeHTML(repo.name.slice(0, 2).toUpperCase())}</span>`;
  const pages = repo.pages_detected && repo.pages_url ? `<a href="${escapeHTML(repo.pages_url)}" target="_blank" rel="noreferrer">${t('page')}</a>` : `<span class="disabled">${t('no_page')}</span>`;
  const status = String(repo.sync_status || 'REVIEW').toLowerCase();
  card.innerHTML = `<div class="repo-top">${avatar}<div class="repo-heading"><a class="repo-name" href="${escapeHTML(repo.url)}" target="_blank" rel="noreferrer">${escapeHTML(repo.name)}</a><span class="repo-layer">${escapeHTML(repo.layer || 'unmapped')}</span></div><span class="category-badge">${escapeHTML(categoryLabel(repo.category))}</span></div><p class="repo-desc">${escapeHTML(desc)}</p><p class="repo-role"><span>${t('role')} //</span> ${escapeHTML(roleText)}</p><div class="repo-footer"><span class="repo-update"><i class="status-dot"></i><time datetime="${escapeHTML(repo.last_pushed || '')}" title="${escapeHTML(formatDate(repo.last_pushed))}">${escapeHTML(relativeTime(repo.last_pushed))}</time></span><span class="sync-badge sync-${status}">${escapeHTML(statusLabel(repo.sync_status || 'REVIEW'))}</span><span class="repo-links">${pages}<a href="${escapeHTML(repo.url)}" target="_blank" rel="noreferrer">${t('code')}</a></span></div>`;
  const image = card.querySelector('.repo-image');
  if (image) image.addEventListener('error', () => { const fallback = document.createElement('span'); fallback.className = 'repo-avatar avatar-fallback'; fallback.textContent = repo.name.slice(0, 2).toUpperCase(); image.replaceWith(fallback); });
  return card;
}

function renderRepos() {
  const repos = filteredRepos();
  const grid = $('#repo-grid');
  grid.replaceChildren(...repos.map(createRepoCard));
  $('#empty-state').hidden = repos.length !== 0;
  $('#result-count').textContent = repos.length;
  if (currentView === 'map') renderMap(repos);
}

function renderMap(repos) {
  const nodeRoot = $('#map-nodes');
  const lines = $('#constellation-lines');
  nodeRoot.replaceChildren();
  lines.replaceChildren();
  const total = Math.max(repos.length, 1);
  repos.forEach((repo, index) => {
    const angle = (index / total) * Math.PI * 2 - Math.PI / 2;
    const categoryRadius = { protocol: 23, system: 31, hub: 38, tool: 45, agent: 43, other: 47 }[repo.category] || 45;
    const radius = categoryRadius + (index % 3) * 2;
    const x = 50 + Math.cos(angle) * radius;
    const y = 50 + Math.sin(angle) * radius * .78;
    const color = categoryColors[repo.category] || categoryColors.other;
    const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
    line.setAttribute('x1', '50'); line.setAttribute('y1', '50'); line.setAttribute('x2', x.toFixed(2)); line.setAttribute('y2', y.toFixed(2)); line.style.stroke = color;
    lines.appendChild(line);
    const node = document.createElement('button');
    node.type = 'button'; node.className = 'map-node'; node.style.left = `${x}%`; node.style.top = `${y}%`; node.style.setProperty('--node-color', color); node.title = repo.name;
    node.innerHTML = `<span class="map-tooltip"><strong>${escapeHTML(repo.name)}</strong><small>${escapeHTML(categoryLabel(repo.category))} · ${resonanceScore(repo)}/100</small></span>`;
    node.addEventListener('click', () => { currentView = 'cards'; $$('.view-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.view === 'cards')); $('#constellation').hidden = true; $('#repo-grid').hidden = false; renderRepos(); document.getElementById(repoId(repo.name))?.scrollIntoView({ behavior: 'smooth', block: 'center' }); });
    nodeRoot.appendChild(node);
  });
}

function renderScan() {
  const visible = filteredRepos();
  const active = visible.filter(repo => repo.sync_status === 'ACTIVE' || ageDays(repo.last_pushed) <= 30).length;
  const pages = visible.filter(repo => repo.pages_detected).length;
  const focus = [...visible].sort((a, b) => resonanceScore(a) - resonanceScore(b))[0];
  const body = $('#scan-body');
  const lines = [
    { text: `> ${t('scan_header')}`, className: 'console-accent' },
    { text: `01 // ${visible.length} ${t('scan_nodes')} · ${active} ${t('scan_active')}`, className: '' },
    { text: `02 // ${pages} ${t('scan_pages')} · ${Math.round((pages / Math.max(visible.length, 1)) * 100)}%`, className: 'console-good' },
    { text: `03 // ${t('scan_next')}: ${focus ? focus.name : t('scan_no_focus')}`, className: 'console-warn' },
    { text: `04 // ${t('scan_note')}`, className: '' },
  ];
  body.replaceChildren(...lines.map(line => { const p = document.createElement('p'); p.className = line.className; p.textContent = line.text; return p; }));
  $('#scan-time').textContent = new Intl.DateTimeFormat(currentLang === 'de' ? 'de-DE' : 'en-US', { hour: '2-digit', minute: '2-digit', second: '2-digit' }).format(new Date());
}

function setView(view) {
  currentView = view;
  $$('.view-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.view === view));
  $('#repo-grid').hidden = view !== 'cards';
  $('#constellation').hidden = view !== 'map';
  if (view === 'map') renderMap(filteredRepos());
}

async function loadManifest() {
  try {
    const response = await fetch(`repo_manifest.json?ts=${Date.now()}`, { cache: 'no-store' });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    manifest = await response.json();
    allRepos = Array.isArray(manifest.repositories) ? manifest.repositories : [];
    $('#footer-version').textContent = t('manifest_version').replace('{version}', manifest.version || '—');
    updateStats(); updateInstrument(); renderRepos();
  } catch (error) {
    console.error('Manifest load failed:', error);
    $('#repo-grid').innerHTML = `<div class="empty-state"><span>!</span><strong>${escapeHTML(currentLang === 'de' ? 'Manifest konnte nicht geladen werden' : 'Manifest could not be loaded')}</strong><p>${escapeHTML(error.message)}</p></div>`;
  }
}

function wireEvents() {
  $$('.lang-btn').forEach(btn => btn.addEventListener('click', () => { currentLang = btn.dataset.lang; localStorage.setItem('irsanai_lang', currentLang); applyTranslations(); updateStats(); updateInstrument(); renderRepos(); if (!$('#scan-body .console-placeholder')) renderScan(); }));
  $('#search-box').addEventListener('input', event => { searchQuery = event.target.value; updateStats(); renderRepos(); });
  $$('.filter-btn').forEach(btn => btn.addEventListener('click', () => { currentFilter = btn.dataset.filter; currentLayer = null; $$('.filter-btn').forEach(item => item.classList.toggle('active', item === btn)); $$('.arch-node').forEach(item => item.classList.remove('active')); updateStats(); renderRepos(); }));
  $('#sort-select').addEventListener('change', event => { sortMode = event.target.value; renderRepos(); });
  $$('.view-btn').forEach(btn => btn.addEventListener('click', () => setView(btn.dataset.view)));
  $$('.arch-node').forEach(node => node.addEventListener('click', () => { currentLayer = node.dataset.layer; $$('.arch-node').forEach(item => item.classList.toggle('active', item === node)); const layerName = translations[currentLang].layers[currentLayer] || currentLayer; const count = filteredRepos().length; $('#architecture-detail').textContent = t('layer_focus').replace('{layer}', layerName).replace('{count}', count); updateStats(); renderRepos(); document.querySelector('#explore').scrollIntoView({ behavior: 'smooth', block: 'start' }); }));
  $('#scan-button').addEventListener('click', renderScan); $('#scan-button-secondary').addEventListener('click', renderScan);
  window.addEventListener('keydown', event => { if (event.key === '/' && document.activeElement?.tagName !== 'INPUT') { event.preventDefault(); $('#search-box').focus(); } if (event.key.toLowerCase() === 'r' && document.activeElement?.tagName !== 'INPUT' && document.activeElement?.tagName !== 'SELECT') renderScan(); });
}

applyTranslations();
wireEvents();
loadManifest();
